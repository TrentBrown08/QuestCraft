#!/bin/sh
# Builds everything QuestCraft needs for 26.3 and stages it in dist/release/.
#
#   ./release.sh                 full build + checks
#   ./release.sh --skip-checks   skip the compile/test step
#   ./release.sh --check-links   also verify every download link in mods.json responds
#
# Settings come from questcraft.config.
set -e
root="$(cd "$(dirname "$0")" && pwd)"
cd "$root"

skip_checks=0
check_links=0
for arg in "$@"; do
    case "$arg" in
        --skip-checks) skip_checks=1 ;;
        --check-links) check_links=1 ;;
        *) echo "unknown option $arg"; exit 2 ;;
    esac
done

step() { printf '\n==> %s\n' "$1"; }
fail() { printf '\nERROR: %s\n' "$1" >&2; exit 1; }

# ---- config
[ -f questcraft.config ] || fail "questcraft.config is missing"
# shellcheck disable=SC1091
. ./questcraft.config
[ "$GITHUB_OWNER" != "CHANGE_ME" ] && [ -n "$GITHUB_OWNER" ] || fail "set GITHUB_OWNER in questcraft.config first"

DATA_URL="https://raw.githubusercontent.com/$GITHUB_OWNER/$DATA_REPO/refs/heads/$DATA_BRANCH"
RELEASE_URL="https://github.com/$GITHUB_OWNER/$RELEASE_REPO/releases/download/$RELEASE_TAG"
VIVECRAFT_JAR="vivecraft-26.3-questcraft-fabric.jar"

for tool in java javac jar curl; do
    command -v "$tool" >/dev/null || fail "$tool not found, install a JDK 25 and make sure it's on PATH"
done
java_major="$(java -XshowSettings:properties -version 2>&1 | sed -n 's/.*java.specification.version = //p')"
[ "${java_major:-0}" -ge 25 ] || fail "JDK 25+ needed to build 26.3, found $java_major"

out="$root/dist/release"
rm -rf "$out"
mkdir -p "$out/upload"

# ---- point the launcher at the fork
step "Writing ReleaseConfig for $GITHUB_OWNER"
cat > Pojlib/src/main/java/pojlib/util/ReleaseConfig.java <<EOF
package pojlib.util;

// Where the launcher downloads its version lists and runtimes from.
// Generated by QuestCraft/release.sh from questcraft.config, edit that instead.
public final class ReleaseConfig {
    private ReleaseConfig() {}

    // raw base of the repo + branch holding mods.json, devmods.json and supportedVersions.json
    public static final String DATA_URL = "$DATA_URL";
    public static final String JRE_21_URL = "https://github.com/QuestCraftPlusPlus/android-openjdk-build-multiarch/releases/latest/download/JRE.zip";
    public static final String JRE_25_URL = "$RELEASE_URL/JRE-25.zip";
}
EOF

# the 26.3 vivecraft entry downloads from the release
perl -pi -e "s|\"download_link\": \"[^\"]*vivecraft-26\.3[^\"]*\"|\"download_link\": \"$RELEASE_URL/$VIVECRAFT_JAR\"|" Pojlib/mods.json
grep -q "$RELEASE_URL/$VIVECRAFT_JAR" Pojlib/mods.json || fail "couldn't update the Vivecraft link in mods.json"

# ---- checks
if [ "$skip_checks" = 0 ]; then
    step "Compiling Pojlib + running tests"
    sh Pojlib/scripts/check-pojlib.sh 2>&1 | grep -v '^WARNING' || fail "Pojlib checks failed"
fi

# ---- vivecraft
step "Building Vivecraft 26.3 (OpenXR)"
(cd VivecraftMod && ./gradlew :fabric:build -x test --console=plain -q) || fail "Vivecraft build failed"
cp VivecraftMod/build/libs/vivecraft-26.3-*-fabric.jar "$out/upload/$VIVECRAFT_JAR"

# ---- lwjgl 3.4 + sdl shim
step "Building LWJGL 3.4 bundle with the SDL shim"
sh Pojlib/scripts/build-lwjgl34.sh

# ---- java 25
step "Packaging Java 25"
if [ ! -f dist/JRE-25.zip ]; then
    mkdir -p dist
    (cd dist && sh ../Pojlib/scripts/package-jre25.sh JRE-25.zip)
fi
cp dist/JRE-25.zip "$out/upload/JRE-25.zip"

# ---- data files
cp Pojlib/mods.json Pojlib/supportedVersions.json "$out/"

# ---- optional link check
if [ "$check_links" = 1 ]; then
    step "Checking mods.json download links"
    bad=0
    for url in $(grep -o '"download_link": "[^"]*"' Pojlib/mods.json | cut -d'"' -f4 | sort -u); do
        case "$url" in "$RELEASE_URL"/*) continue ;; esac
        code="$(curl -s -o /dev/null -w '%{http_code}' -r 0-0 -L "$url")"
        if [ "$code" != "200" ] && [ "$code" != "206" ]; then
            echo "  $code  $url"
            bad=$((bad + 1))
        fi
    done
    [ "$bad" = 0 ] && echo "  all links ok" || echo "  $bad broken link(s)"
fi

# ---- summary
cat > "$out/NEXT-STEPS.txt" <<EOF
QuestCraft 26.3 release for $GITHUB_OWNER

1. Create the GitHub release
   repo:  https://github.com/$GITHUB_OWNER/$RELEASE_REPO
   tag:   $RELEASE_TAG
   attach everything in dist/release/upload/:
     - $VIVECRAFT_JAR
     - JRE-25.zip

2. Push Pojlib to your fork so the launcher can read the version lists
   cd Pojlib
   git remote add mine https://github.com/$GITHUB_OWNER/$DATA_REPO.git
   git push mine HEAD:$DATA_BRANCH
   check: $DATA_URL/supportedVersions.json

3. Build the launcher
   - open Pojlib in Android Studio and build the library
   - open QCXR-XR-Wrapper in Unity 2022.3.62f3, build the Android APK

4. Sideload onto the Quest (developer mode on, USB connected)
   adb install -r path/to/QuestCraft.apk

5. Test on the headset: create a 26.3 instance, launch it, and if anything goes wrong grab the log:
   adb logcat -d > questcraft-log.txt
EOF

step "Done"
echo "Release staged in dist/release/"
ls -la "$out/upload"
echo
cat "$out/NEXT-STEPS.txt"
